# Regenerate device/sepolicy/vendor from the stock policy and run the three acceptance checks of TASK.md.
# Results land in docs/RESULTS.md (and tools/out/).  Exit status is non-zero if any check fails.
set -u
cd "$(dirname "$0")/.."
./tools/fetch_deps.sh || exit 1
mkdir -p tools/out
python3 tools/cil2te.py > tools/out/cil2te.log || { cat tools/out/cil2te.log; exit 1; }
rc=0
python3 tools/check_compile.py  --md tools/out/check1.md > tools/out/check1.log 2>&1 || rc=1
python3 tools/check_labels.py   --md tools/out/check2.md > tools/out/check2.log 2>&1 || rc=1
python3 tools/check_services.py --md tools/out/check3.md > tools/out/check3.log 2>&1 || rc=1
python3 tools/check_manifest.py --md tools/out/check4.md > tools/out/check4.log 2>&1 || rc=1
{
    echo "# Acceptance check results"
    echo
    echo "Generated by \`tools/run_checks.sh\` on $(date -u +%Y-%m-%d) (host tools: secilc $(dpkg-query -W -f="\${Version}" secilc 2>/dev/null), checkpolicy $(dpkg-query -W -f="\${Version}" checkpolicy 2>/dev/null), libselinux $(dpkg-query -W -f="\${Version}" libselinux1 2>/dev/null))."
    echo "Converter summary: see \`docs/cil2te_report.md\`."
    echo
    for f in check1 check2 check3 check4; do
        cat tools/out/$f.md
        echo
    done
} > docs/RESULTS.md
echo "results: docs/RESULTS.md (rc=$rc)"
exit $rc
