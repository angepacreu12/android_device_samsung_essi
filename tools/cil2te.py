"""cil2te.py - regenerate device/sepolicy/vendor from Samsung's compiled vendor policy.

Input  (read-only, see TASK.md):
  reference/stock/vendor/etc/selinux/vendor_sepolicy.cil     Samsung's vendor policy (CIL)
  reference/stock/vendor/etc/selinux/plat_pub_versioned.cil  Samsung's view of the public platform policy
  reference/stock/vendor/etc/selinux/*_contexts, vendor_mac_permissions.xml
  reference/baseline/vendor/etc/selinux/*                    what our tree builds without any device policy
                                                             (= the AOSP system/sepolicy/vendor + Lineage baseline; frozen)
  reference/system/*/selinux/*.cil                           our platform policy (for genfscon conflicts)

Output: device/sepolicy/vendor/ (wiped and rewritten) and docs/cil2te_report.md.

The conversion is mechanical: every CIL statement kind Samsung uses has a 1:1 kernel-policy-language
equivalent.  Public platform types are unversioned (foo_202404 -> foo), auto-generated attributes
(base_typeattr_N) are turned back into { a b -c } set expressions, and everything the baseline already
declares is not declared again.  Rules that name a platform type Samsung's system has but ours does not
are dropped (and counted) unless the type is in PLATFORM_COMPAT, in which case it is declared here.
"""
import argparse
import collections
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# Samsung *platform* (public) types that our platform lacks but that Samsung's vendor contexts files
# or boot-critical vendor daemons need.  They are declared in samsung_platform_compat.te with the
# attributes Samsung gave them.  Every other Samsung-only platform type makes the rules naming it dead
# on /e/OS (the objects never exist), so those rules are dropped and reported.
PLATFORM_COMPAT = [
    "hal_tee_service",            # vendor_service_contexts: TEEGRIS tee_service_daemon
    "hal_tee_hwservice",          # vendor_hwservice_contexts
    "hal_teeregistry_hwservice",  # vendor_hwservice_contexts
    "pa_daemon_device",           # /dev node used by the TEEGRIS pa_daemon (label added in file_contexts)
    "secure_storage_device",      # /dev node used by tzdaemon / tee daemons
    "system_integrity_device",    # /dev node used by the ICCC / proca stack
]

# Property namespaces a vendor property_contexts may define (system/sepolicy/build/soong/selinux_contexts.go).
VENDOR_PROP_PREFIXES = ("ctl.odm.", "ctl.vendor.", "ctl.start$odm.", "ctl.start$vendor.", "ctl.stop$odm.",
                        "ctl.stop$vendor.", "init.svc.odm.", "init.svc.vendor.", "ro.boot.", "ro.hardware.",
                        "ro.odm.", "ro.vendor.", "odm.", "persist.odm.", "persist.vendor.", "vendor.")

GENERATED_HEADER = "# Generated by tools/cil2te.py from Samsung A566BXXS6AYGE vendor_sepolicy.cil. Do not edit.\n"


# --------------------------------------------------------------------------- CIL parsing

def tokenize(text):
    tok = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c in " \t\r\n":
            i += 1
        elif c == ";":  # comment to end of line
            while i < n and text[i] != "\n":
                i += 1
        elif c in "()":
            tok.append(c)
            i += 1
        elif c == '"':
            j = text.index('"', i + 1)
            tok.append(text[i:j + 1])
            i = j + 1
        else:
            j = i
            while j < n and text[j] not in " \t\r\n()\"":
                j += 1
            tok.append(text[i:j])
            i = j
    return tok


def parse(text):
    """Return a list of top-level s-expressions (nested Python lists / strings)."""
    tok = tokenize(text)
    stack = [[]]
    for t in tok:
        if t == "(":
            stack.append([])
        elif t == ")":
            e = stack.pop()
            stack[-1].append(e)
        else:
            stack[-1].append(t)
    if len(stack) != 1:
        raise ValueError("unbalanced parentheses")
    return stack[0]


def sexp(e):
    if isinstance(e, list):
        return "(" + " ".join(sexp(x) for x in e) + ")"
    return e


def read(path):
    with open(path, errors="replace") as f:
        return f.read()


def decls(text, kind):
    return set(re.findall(r"^\(%s (\S+)\)" % kind, text, re.M))


# --------------------------------------------------------------------------- the converter

class Converter:
    def __init__(self, ref, vers, keep_neverallows=False):
        self.vers = vers
        self.keep_neverallows = keep_neverallows
        self.suffix = "_" + vers
        stock_dir = os.path.join(ref, "stock/vendor/etc/selinux")
        ours_dir = os.path.join(ref, "baseline/vendor/etc/selinux")   # frozen no-device-policy build, see reference/baseline/README.md
        if not os.path.isdir(ours_dir):
            raise SystemExit("reference/baseline missing: the converter needs the frozen baseline build (reference/ours is the current image)")
        self.stock_dir, self.ours_dir = stock_dir, ours_dir
        self.stock_cil = read(os.path.join(stock_dir, "vendor_sepolicy.cil"))
        stock_ppv = read(os.path.join(stock_dir, "plat_pub_versioned.cil"))
        ours_ppv = read(os.path.join(ours_dir, "plat_pub_versioned.cil"))
        ours_vendor = read(os.path.join(ours_dir, "vendor_sepolicy.cil"))
        plat = (read(os.path.join(ref, "system/system/selinux/plat_sepolicy.cil"))
                + read(os.path.join(ref, "system/system_ext/selinux/system_ext_sepolicy.cil"))
                + read(os.path.join(ref, "system/product/selinux/product_sepolicy.cil")))

        # Public (platform) namespace as our system knows it.
        self.pub_types = decls(ours_ppv, "type")
        self.pub_attrs = {a for a in decls(ours_ppv, "typeattribute")
                          if not a.endswith(self.suffix) and not a.startswith("base_typeattr_")}
        # Public namespace as Samsung's system knows it.
        sams_pub_types = decls(stock_ppv, "type")
        sams_pub_attrs = {a for a in decls(stock_ppv, "typeattribute")
                          if not a.endswith(self.suffix) and not a.startswith("base_typeattr_")}
        self.missing_types = sams_pub_types - self.pub_types
        self.missing_attrs = sams_pub_attrs - self.pub_attrs
        # Baseline vendor policy (system/sepolicy/vendor + Lineage), already in every build.
        self.base_types = decls(ours_vendor, "type") - self.pub_types
        self.base_attrs = {a for a in decls(ours_vendor, "typeattribute")
                           if not a.startswith("base_typeattr_")} - self.pub_attrs
        # Vendor namespace declared by Samsung.
        self.stock_types = decls(self.stock_cil, "type")
        self.stock_attrs = {a for a in decls(self.stock_cil, "typeattribute")
                            if not a.startswith("base_typeattr_")}
        self.compat = [t for t in PLATFORM_COMPAT if t in self.missing_types]
        # Samsung *system-side* contexts (reference/stock/system/*): labels that Samsung's system
        # policy assigns and that vendor rules depend on.  Recover the ones the vendor side may set.
        rule_lines = "\n".join(l for l in self.stock_cil.splitlines()
                               if l.startswith(("(allow", "(dontaudit", "(typetransition", "(auditallow")))
        self.stock_refs = set(re.findall(r"([A-Za-z0-9_.\-]+)%s\b" % re.escape(self.suffix), rule_lines))
        self.sys_fc, self.sys_prop, self.sys_prop_unusable, self.sys_files = [], [], collections.defaultdict(list), []
        sysdir = os.path.join(ref, "stock/system")
        if os.path.isdir(sysdir):
            for fn in sorted(os.listdir(sysdir)):
                path = os.path.join(sysdir, fn)
                if fn.endswith("file_contexts"):
                    self.sys_files.append(fn)
                    for line in read(path).splitlines():
                        line = line.split("#")[0].strip()
                        parts = line.split()
                        if len(parts) < 2 or not parts[-1].startswith("u:"):
                            continue
                        t = parts[-1].split(":")[2]
                        if t in self.missing_types and t in self.stock_refs and not re.match(
                                r"^/\(?(system|system_ext|product|apex)\b", parts[0]):
                            self.sys_fc.append((line, t))
                            if t not in self.compat:
                                self.compat.append(t)
                elif fn.endswith("property_contexts"):
                    self.sys_files.append(fn)
                    for line in read(path).splitlines():
                        line = line.split("#")[0].strip()
                        parts = line.split()
                        con = [x for x in parts[1:] if x.startswith("u:")]
                        if not con:
                            continue
                        t = con[0].split(":")[2]
                        if t in self.missing_types and t in self.stock_refs:
                            if parts[0].startswith(VENDOR_PROP_PREFIXES):
                                self.sys_prop.append((line, t))
                                if t not in self.compat:
                                    self.compat.append(t)
                            else:
                                self.sys_prop_unusable[t].append(parts[0])

        # Attribute memberships already present in the platform / baseline (to avoid re-stating them).
        self.known_members = set()
        for text in (ours_ppv, ours_vendor):
            for st in parse(text):
                if st and st[0] == "typeattributeset" and isinstance(st[2], list) and all(isinstance(x, str) for x in st[2]):
                    for m in st[2]:
                        self.known_members.add((self.unver(m), st[1]))
        # Attributes Samsung's platform gives to the compat types.
        self.compat_attrs = collections.defaultdict(list)
        for st in parse(stock_ppv):
            if st and st[0] == "typeattributeset" and isinstance(st[2], list) and all(isinstance(x, str) for x in st[2]):
                for m in st[2]:
                    if self.unver(m) in self.compat and st[1] in self.pub_attrs \
                            and st[1] != "coredomain" and not st[1].startswith("system_"):
                        self.compat_attrs[self.unver(m)].append(st[1])
        for t in self.compat:
            if "property_type" in self.compat_attrs.get(t, []) and "vendor_property_type" not in self.compat_attrs[t]:
                self.compat_attrs[t].append("vendor_property_type")   # a vendor-declared property type

        # genfscon already defined by the platform or the baseline: (fs, path) -> type
        self.known_genfs = {}
        for text in (plat, ours_vendor):
            for m in re.finditer(r'^\(genfscon (\S+) "([^"]*)" \(u object_r (\S+) ', text, re.M):
                self.known_genfs[(m.group(1), m.group(2))] = m.group(3)
        # type_transitions already in the baseline: (src, tgt, class, name) -> result
        self.known_tt = {}
        for st in parse(ours_vendor):
            if st and st[0] == "typetransition":
                key, res = self.tt_key(st)
                self.known_tt[key] = res

        self.report = collections.OrderedDict()
        self.dropped = collections.defaultdict(list)
        self.files = collections.defaultdict(list)
        self.base_sets = {}      # base_typeattr_N -> expression string
        self.members = collections.defaultdict(list)   # vendor type -> attrs
        self.extra_members = []  # (type, attr) for types not declared here
        self.domains = set()
        self.unsupported = []

    # ------------------------------------------------------------------ names
    def unver(self, name):
        return name[:-len(self.suffix)] if name.endswith(self.suffix) else name

    def classify(self, raw):
        """Return (kind, name): kind in self, pub_type, pub_attr, base_type, base_attr, type, attr, compat,
        set, missing, unknown."""
        n = self.unver(raw)
        if n == "self":
            return "self", n
        if n.startswith("base_typeattr_"):
            return "set", n
        if n in self.compat:
            return "compat", n
        if n in self.missing_types or n in self.missing_attrs:
            return "missing", n
        if n in self.pub_types:
            return "pub_type", n
        if n in self.pub_attrs:
            return "pub_attr", n
        if n in self.base_types:
            return "base_type", n
        if n in self.base_attrs:
            return "base_attr", n
        if n in self.stock_types:
            return "type", n
        if n in self.stock_attrs:
            return "attr", n
        if n in self.aliases:
            return "type", n
        return "unknown", n

    def tt_key(self, st):
        if len(st) == 6:
            return (self.unver(st[1]), self.unver(st[2]), st[3], st[4]), self.unver(st[5])
        return (self.unver(st[1]), self.unver(st[2]), st[3], None), self.unver(st[4])

    # ------------------------------------------------------------------ set expressions
    def expr(self, e):
        """Convert a CIL type-set expression to (positives, negatives, all) using kernel language
        semantics.  Returns None if a form the kernel language cannot express shows up."""
        if isinstance(e, str):
            return [e], [], False
        if not e:
            return [], [], False
        if isinstance(e[0], str) and e[0] in ("and", "or", "not", "all", "xor"):
            op = e[0]
            if op == "all":
                return [], [], True
            if op == "not":
                p, n, a = self.expr(e[1]) if len(e) == 2 else self.expr(e[1:])
                if n or a:
                    return None
                return [], p, True
            if op == "or":
                pos, neg, al = [], [], False
                for x in e[1:]:
                    r = self.expr(x)
                    if r is None or r[1] or r[2]:
                        return None
                    pos += r[0]
                return pos, [], False
            if op == "and":
                pos, neg, al = [], [], False
                for x in e[1:]:
                    r = self.expr(x)
                    if r is None:
                        return None
                    p, n, a = r
                    if a and not n:      # (all) as a conjunct
                        al = True
                    elif a and n:        # (not (...))
                        neg += n
                    elif not n:
                        pos += p
                    else:
                        return None
                if al and pos:
                    al = False           # "all and X" == X
                return pos, neg, al
            return None
        # plain list of names
        return list(e), [], False

    def set_string(self, names_expr, ctx):
        """Return the kernel-language string for a set expression, or None to drop the rule."""
        r = self.expr(names_expr)
        if r is None:
            self.unsupported.append("set expression %s (%s)" % (sexp(names_expr), ctx))
            return None
        pos, neg, al = r
        p2, n2 = [], []
        for x in pos:
            k, n = self.classify(x)
            if k in ("missing", "unknown"):
                self.dropped["set member " + k].append("%s in %s" % (n, ctx))
                continue
            if k == "set":
                s = self.base_sets.get(n)
                if s is None:
                    return None
                p2.append(s)
            else:
                p2.append(n)
        for x in neg:
            k, n = self.classify(x)
            if k in ("missing", "unknown"):
                continue                 # removing a type that does not exist changes nothing
            n2.append(n)
        if al:
            if not n2:
                return "*"
            return "~{ %s }" % " ".join(n2)
        if not p2:
            return None
        if len(p2) == 1 and not n2:
            return p2[0]
        return "{ %s }" % " ".join(p2 + ["-" + x for x in n2])

    def name(self, raw, ctx):
        """Convert a single subject/object name; None means drop the rule."""
        k, n = self.classify(raw)
        if k == "set":
            return self.base_sets.get(n)
        if k == "missing":
            self.dropped["names Samsung-only platform type"].append("%s: %s" % (n, ctx))
            return None
        if k == "unknown":
            self.dropped["names unknown type"].append("%s: %s" % (n, ctx))
            return None
        return n

    # ------------------------------------------------------------------ file placement
    def category(self, t):
        attrs = set(self.members.get(t, []))
        if t in self.domains:
            return t + ".te"
        if t.endswith("_exec") and t[:-5] in self.domains:
            return t[:-5] + ".te"
        if attrs & {"property_type"} or t.endswith("_prop"):
            return "property.te"
        if attrs & {"service_manager_type"} or t.endswith("_service"):
            return "service.te"
        if attrs & {"hwservice_manager_type"} or t.endswith("_hwservice"):
            return "hwservice.te"
        if attrs & {"vndservice_manager_type"}:
            return "vndservice.te"
        if attrs & {"dev_type"} or t.endswith("_device"):
            return "device.te"
        if attrs & {"file_type", "fs_type", "data_file_type"} or "file" in t:
            return "file.te"
        return "misc_types.te"

    def owner_file(self, src_raw, tgt_raw):
        for raw in (src_raw, tgt_raw):
            k, n = self.classify(raw)
            if k in ("type", "compat"):
                return self.category(n)
        for raw in (src_raw, tgt_raw):
            k, n = self.classify(raw)
            if k in ("pub_type", "base_type", "pub_attr", "base_attr", "attr"):
                return "platform_and_baseline_domains.te"
        return "misc.te"

    def emit(self, fname, line):
        self.files[fname].append(line)

    # ------------------------------------------------------------------ statements
    def run(self):
        stmts = parse(self.stock_cil)
        counts = collections.Counter(st[0] for st in stmts)
        self.report["input statements"] = dict(counts)

        # pass 0: aliases, domains, attribute memberships, base_typeattr sets
        self.aliases = {}
        for st in stmts:
            if st[0] == "typealiasactual":
                self.aliases[st[1]] = self.unver(st[2])
        for st in stmts:
            if st[0] == "typeattributeset" and st[1] == "domain":
                for m in st[2]:
                    self.domains.add(self.unver(m))
        for st in stmts:
            if st[0] == "typeattributeset":
                attr = st[1]
                if attr.startswith("base_typeattr_"):
                    continue
                if isinstance(st[2], list) and any(isinstance(x, list) for x in st[2]) or (
                        isinstance(st[2], list) and st[2] and st[2][0] in ("and", "or", "not", "all")):
                    s = self.set_string(st[2], sexp(st))
                    if s is None:
                        continue
                    # a named attribute defined by an expression: kernel language has no direct form,
                    # so it cannot be a member list; report and skip.
                    self.unsupported.append("attribute %s defined by expression %s" % (attr, sexp(st[2])))
                    continue
                ak, an = self.classify(attr)
                if ak in ("missing", "unknown"):
                    self.dropped["membership in Samsung-only platform attribute"].append(sexp(st)[:160])
                    continue
                for m in st[2]:
                    mk, mn = self.classify(m)
                    if mk in ("missing", "unknown"):
                        self.dropped["membership of Samsung-only platform type"].append("%s in %s" % (mn, an))
                        continue
                    if (mn, an) in self.known_members:
                        continue
                    if mk in ("type", "compat"):
                        self.members[mn].append(an)
                    else:
                        self.extra_members.append((mn, an))
        # base_typeattr sets (may reference each other, resolve iteratively)
        pending = [st for st in stmts if st[0] == "typeattributeset" and st[1].startswith("base_typeattr_")]
        for _ in range(5):
            rest = []
            for st in pending:
                n = self.unver(st[1])
                s = self.set_string(st[2], "typeattributeset " + n)
                if s is None and any(isinstance(x, str) and self.unver(x).startswith("base_typeattr_") for x in sexp(st[2]).replace("(", " ").replace(")", " ").split()):
                    rest.append(st)
                    continue
                self.base_sets[n] = s   # None => rules using it are dropped
            pending = rest
            if not pending:
                break

        # pass 1: declarations
        attrs_out = [GENERATED_HEADER, "# Attributes declared by Samsung's vendor policy.\n"]
        for a in sorted(self.stock_attrs):
            if a in self.pub_attrs or a in self.base_attrs:
                self.dropped["attribute already declared by platform/baseline"].append(a)
                continue
            attrs_out.append("attribute %s;" % a)
        self.files["attributes"] = attrs_out

        declared = 0
        for t in sorted(self.stock_types):
            if t in self.pub_types or t in self.base_types:
                self.dropped["type already declared by platform/baseline"].append(t)
                continue
            f = self.category(t)
            attrs = sorted(set(self.members.get(t, [])))
            self.emit(f, "type %s%s;" % (t, "".join(", " + a for a in attrs)))
            declared += 1
        self.report["types declared"] = declared
        origin = {t: "vendor contexts / PLATFORM_COMPAT" for t in PLATFORM_COMPAT}
        for line, t in self.sys_fc:
            origin.setdefault(t, "labels %s" % line.split()[0])
        for line, t in self.sys_prop:
            origin.setdefault(t, "labels property %s" % line.split()[0])
        self.emit("samsung_platform_compat.te",
                  "# Samsung platform (system-side) types that our platform lacks, declared here as vendor types.")
        for t in self.compat:
            attrs = sorted(a for a in set(self.compat_attrs.get(t, [])) | set(self.members.get(t, []))
                           if a != "coredomain" and not a.startswith("system_"))   # coredomain_socket is an object attr, keep it
            self.emit("samsung_platform_compat.te", "type %s%s;  # %s" % (t, "".join(", " + a for a in attrs), origin.get(t, "")))
        for (t, a) in sorted(set(self.extra_members)):
            if a in self.pub_attrs and t in self.pub_types:
                fname = "platform_and_baseline_domains.te"
            else:
                fname = self.category(t) if t in self.stock_types else "platform_and_baseline_domains.te"
            self.emit(fname, "typeattribute %s %s;" % (t, a))
        for st in stmts:
            if st[0] == "typealias":
                alias = st[1]
                actual = self.aliases.get(alias)
                if actual is None:
                    continue
                k, n = self.classify(actual)
                if k in ("missing", "unknown"):
                    self.dropped["alias of missing type"].append(alias)
                    continue
                self.emit(self.category(n) if n in self.stock_types else "misc_types.te",
                          "typealias %s alias %s;" % (n, alias))
            elif st[0] == "expandtypeattribute":
                for a in st[1]:
                    k, n = self.classify(a)
                    if k in ("attr",):
                        self.emit("attributes", "expandattribute %s %s;" % (n, st[2]))
                    else:
                        self.dropped["expandattribute on non-vendor attribute"].append(n)

        # pass 2: rules
        converted = collections.Counter()
        exclusions = []
        excl_path = os.path.join(HERE, "cil2te_exclusions.txt")
        if os.path.exists(excl_path):
            for raw in open(excl_path):
                body, _, reason = raw.partition("#")
                body = body.strip()
                if body:
                    exclusions.append((re.compile(body), reason.strip() or body))
        for st in stmts:
            kind = st[0]
            if kind in ("type", "typeattribute", "typeattributeset", "roletype", "typealias",
                        "typealiasactual", "expandtypeattribute"):
                continue
            ctx = sexp(st)[:200]
            full = sexp(st)
            if kind in ("neverallow", "neverallowx") and not self.keep_neverallows:
                # Samsung's neverallows assert things about *Samsung's* platform (their app_domain()
                # and hal_attribute*() macro expansions, expanded attributes, user-build exclusions).
                # On our platform 17 of them fail the build's sepolicy-analyze / recovery checks and
                # they have no runtime effect, so they are not converted.  --neverallows keep emits them.
                self.dropped["Samsung neverallow (compile-time assertion about Samsung's platform, not converted)"].append(ctx)
                continue
            hit = next((reason for rx, reason in exclusions if rx.search(full)), None)
            if hit:
                self.dropped["excluded by tools/cil2te_exclusions.txt"].append("%s -- %s" % (ctx, hit))
                continue
            if kind in ("allow", "dontaudit", "neverallow", "auditallow"):
                s = self.name(st[1], ctx)
                t = self.name(st[2], ctx)
                if s is None or t is None:
                    continue
                cls, perms = st[3][0], st[3][1]
                if perms == ["all"] or perms == "all":
                    p = "*"
                else:
                    p = "{ %s }" % " ".join(perms)
                if kind == "neverallow" and cls == "process" and perms == ["ptrace"] and s.startswith("{ domain -"):
                    # Samsung's app_domain() macro was expanded for a user build; AOSP's adds
                    # userdebug_or_eng(`-llkd') and our platform is userdebug (llkd may ptrace apps).
                    s = s[:-1].rstrip() + " -llkd }"
                    self.report["neverallow ptrace rules given the userdebug -llkd exclusion"] = \
                        self.report.get("neverallow ptrace rules given the userdebug -llkd exclusion", 0) + 1
                if kind == "neverallow" and s == "mediacodec" and t == "domain" and cls == "tcp_socket":
                    # AOSP: neverallow mediacodec { domain userdebug_or_eng(`-su') }:tcp_socket *;
                    t = "{ domain -su }"
                line = "%s %s %s:%s %s;" % (kind, s, t, cls, p)
                fname = "neverallows.te" if kind == "neverallow" else self.owner_file(st[1], st[2])
                self.emit(fname, line)
                converted[kind] += 1
            elif kind in ("allowx", "dontauditx", "neverallowx", "auditallowx"):
                s = self.name(st[1], ctx)
                t = self.name(st[2], ctx)
                if s is None or t is None:
                    continue
                op, cls, vals = st[3][0], st[3][1], st[3][2]
                out = []
                for v in vals:
                    if isinstance(v, list) and v[0] == "range":
                        out.append("%s-%s" % (v[1], v[2]))
                    else:
                        out.append(v)
                te = {"allowx": "allowxperm", "dontauditx": "dontauditxperm",
                      "neverallowx": "neverallowxperm", "auditallowx": "auditallowxperm"}[kind]
                line = "%s %s %s:%s %s { %s };" % (te, s, t, cls, op, " ".join(out))
                fname = "neverallows.te" if kind == "neverallowx" else self.owner_file(st[1], st[2])
                self.emit(fname, line)
                converted[kind] += 1
            elif kind == "typetransition":
                key, res = self.tt_key(st)
                s = self.name(st[1], ctx)
                t = self.name(st[2], ctx)
                r = self.name(res, ctx)
                if s is None or t is None or r is None:
                    continue
                if key in self.known_tt:
                    if self.known_tt[key] != r:
                        self.dropped["type_transition conflicts with baseline"].append(
                            "%s (baseline -> %s, stock -> %s)" % (ctx, self.known_tt[key], r))
                    continue
                cls, fn = key[2], key[3]
                if fn is None:
                    line = "type_transition %s %s:%s %s;" % (s, t, cls, r)
                else:
                    line = "type_transition %s %s:%s %s %s;" % (s, t, cls, r, fn)
                self.emit(self.owner_file(st[1], res), line)
                converted[kind] += 1
            elif kind == "genfscon":
                fs, path, con = st[1], st[2].strip('"'), st[3]
                t = self.unver(con[2])
                k, n = self.classify(t)
                if k in ("missing", "unknown"):
                    self.dropped["genfscon with missing type"].append(ctx)
                    continue
                known = self.known_genfs.get((fs, path))
                if known is not None:
                    key = "genfscon already defined by platform/baseline (same type)" if known == n \
                        else "genfscon conflicts with platform/baseline"
                    self.dropped[key].append("%s %s: ours %s, stock %s" % (fs, path, known, n))
                    continue
                self.emit("genfs_contexts", "genfscon %s %s u:object_r:%s:s0" % (fs, path, n))
                converted[kind] += 1
            else:
                self.unsupported.append(ctx)
        self.report["rules converted"] = dict(converted)
        self.report["rules dropped"] = {k: len(v) for k, v in self.dropped.items()}
        self.report["unsupported"] = len(self.unsupported)

    # ------------------------------------------------------------------ contexts files
    def import_contexts(self, outdir):
        """Copy Samsung's contexts files, minus what the baseline already provides."""
        def entries(path):
            out = []
            if not os.path.exists(path):
                return out
            for line in read(path).splitlines():
                s = line.split("#")[0].strip()
                if s:
                    out.append(s)
            return out

        def keyed(lines):
            d = collections.OrderedDict()
            for l in lines:
                parts = l.split()
                d[parts[0]] = l
            return d

        imported = {}
        for stock_name, base_name, out_name in [
                ("vendor_file_contexts", "vendor_file_contexts", "file_contexts"),
                ("vendor_property_contexts", "vendor_property_contexts", "property_contexts"),
                ("vendor_service_contexts", "vendor_service_contexts", "service_contexts"),
                ("vendor_hwservice_contexts", "vendor_hwservice_contexts", "hwservice_contexts"),
                ("vndservice_contexts", "vndservice_contexts", "vndservice_contexts"),
                ("vendor_seapp_contexts", "vendor_seapp_contexts", "seapp_contexts"),
                ("vendor_keystore2_key_contexts", "vendor_keystore2_key_contexts", "keystore2_key_contexts")]:
            stock = entries(os.path.join(self.stock_dir, stock_name))
            base = entries(os.path.join(self.ours_dir, base_name))
            # keys the system side already defines with the same context: libselinux logs
            # "Multiple same specifications" for every duplicate it loads, so leave them out too
            sysdir = os.path.join(os.path.dirname(os.path.dirname(self.ours_dir.rstrip("/"))), "..", "system")
            sysdir = os.path.normpath(os.path.join(self.ours_dir, "../../../../system"))
            kind = out_name
            for part, prefix in (("system", "plat"), ("system_ext", "system_ext"), ("product", "product")):
                if kind in ("file_contexts", "seapp_contexts", "vndservice_contexts", "keystore2_key_contexts"):
                    break
                base += entries(os.path.join(sysdir, part, "selinux", "%s_%s" % (prefix, kind)))
            if out_name == "seapp_contexts":
                kept = [l for l in stock if l not in base]
                skipped = []
            else:
                bk = keyed(base)
                kept, skipped = [], []
                seen = set()
                for l in stock:
                    k = l.split()[0]
                    if k in seen:
                        self.dropped["contexts key listed twice in the stock file"].append("%s: %s" % (out_name, l))
                        continue
                    seen.add(k)
                    if k in bk:
                        skipped.append("%s (baseline: %s)" % (l, bk[k].split()[-1]))
                        if bk[k].split()[-1] != l.split()[-1]:
                            self.dropped["contexts key already set differently by baseline"].append(
                                "%s: %s" % (out_name, l))
                    else:
                        kept.append(l)
            extra = [l for l, _ in (self.sys_fc if out_name == "file_contexts" else
                                    self.sys_prop if out_name == "property_contexts" else [])]
            if not kept and not extra:
                continue
            with open(os.path.join(outdir, out_name), "w") as f:
                f.write(GENERATED_HEADER.replace("vendor_sepolicy.cil", stock_name))
                if skipped:
                    f.write("# %d entries already provided by the AOSP/Lineage baseline were left out.\n" % len(skipped))
                f.write("\n".join(kept) + "\n")
                if extra:
                    f.write("\n# Labels Samsung's *system* contexts assign (reference/stock/system/) to objects that\n"
                            "# vendor rules depend on; the types are declared in samsung_platform_compat.te.\n")
                    f.write("\n".join(extra) + "\n")
            imported[out_name] = (len(stock), len(kept) + len(extra))
        # mac_permissions.xml: Samsung's is already key-expanded; insertkeys.py passes hex signatures through.
        src = os.path.join(self.stock_dir, "vendor_mac_permissions.xml")
        if os.path.exists(src):
            shutil.copyfile(src, os.path.join(outdir, "mac_permissions.xml"))
            imported["mac_permissions.xml"] = (1, 1)
        self.report["contexts imported (stock entries, kept)"] = imported

    # ------------------------------------------------------------------ output
    def write(self, outdir):
        if os.path.isdir(outdir):
            for f in os.listdir(outdir):
                os.unlink(os.path.join(outdir, f))
        os.makedirs(outdir, exist_ok=True)
        for fname, lines in self.files.items():
            body = lines if fname == "attributes" else [GENERATED_HEADER] + lines
            with open(os.path.join(outdir, fname), "w") as f:
                f.write("\n".join(body) + "\n")
        self.import_contexts(outdir)
        with open(os.path.join(outdir, "README.md"), "w") as f:
            f.write("# essi vendor sepolicy (generated)\n\n"
                    "Everything in this directory is generated by `tools/cil2te.py` from Samsung's stock\n"
                    "A566BXXS6AYGE vendor policy (`reference/stock/vendor/etc/selinux`). Re-run the tool instead\n"
                    "of editing files here; see `docs/APPROACH.md` and `docs/cil2te_report.md`.\n\n"
                    "Wired into the build by `BOARD_VENDOR_SEPOLICY_DIRS` in `device/BoardConfig.mk`.\n")

    def write_report(self, path):
        lines = ["# cil2te report", "",
                 "Generated by `tools/cil2te.py` (policy version %s)." % self.vers, ""]
        lines += ["## Summary", ""]
        for k, v in self.report.items():
            lines.append("- **%s**: `%s`" % (k, v))
        lines += ["", "## Samsung-only platform types",
                  "",
                  "Samsung's public platform policy declares %d types / %d attributes that ours does not. %d of "
                  "those types are declared here as vendor types (`samsung_platform_compat.te`): `%s`."
                  % (len(self.missing_types), len(self.missing_attrs), len(self.compat), "`, `".join(self.compat)),
                  ""]
        lines += ["## Samsung system-side contexts (reference/stock/system/)", ""]
        if not self.sys_files:
            lines.append("No Samsung system contexts files found.")
        else:
            lines.append("Files scanned: `%s`." % "`, `".join(self.sys_files))
            lines.append("- file_contexts entries recovered (Samsung-only type, used by vendor rules, path not under a "
                         "system partition): %d" % len(self.sys_fc))
            lines += ["  - `%s`" % l for l, _ in self.sys_fc]
            lines.append("- property_contexts entries recovered (vendor-settable namespace): %d" % len(self.sys_prop))
            lines += ["  - `%s`" % l for l, _ in self.sys_prop]
            if self.sys_prop_unusable:
                lines.append("- properties Samsung labels with a type vendor rules use, but in a namespace only the "
                             "system side may label (cannot be recovered from vendor policy):")
                for t, keys in sorted(self.sys_prop_unusable.items()):
                    lines.append("  - `%s`: %s" % (t, ", ".join("`%s`" % k for k in keys[:10])))
            used = collections.Counter(x.split(":")[0] for x in self.dropped.get("names Samsung-only platform type", []))
            notfound = [(t, n) for t, n in used.most_common() if t not in self.compat and t not in self.sys_prop_unusable]
            lines.append("- Samsung-only types named by dropped rules and *not* labeled in the files above (top 40 of %d, "
                         "with rule counts); they must be defined in Samsung's system_ext/product contexts or be "
                         "framework services: %s" % (len(notfound), ", ".join("`%s` %d" % x for x in notfound[:40])))
        lines.append("")
        for k, v in sorted(self.dropped.items(), key=lambda kv: -len(kv[1])):
            lines += ["## Dropped: %s (%d)" % (k, len(v)), ""]
            shown = v if len(v) <= 60 else v[:60] + ["... %d more" % (len(v) - 60)]
            lines += ["- `%s`" % x.replace("`", "'") for x in shown]
            lines.append("")
        if self.unsupported:
            lines += ["## Unsupported statements (%d)" % len(self.unsupported), ""]
            lines += ["- `%s`" % x for x in self.unsupported[:60]]
            lines.append("")
        with open(path, "w") as f:
            f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ref", default=os.path.join(ROOT, "reference"))
    ap.add_argument("--out", default=os.path.join(ROOT, "device/sepolicy/vendor"))
    ap.add_argument("--report", default=os.path.join(ROOT, "docs/cil2te_report.md"))
    ap.add_argument("--neverallows", choices=["drop", "keep"], default="drop",
                    help="keep: also convert Samsung's neverallow rules (they fail the build's checks on our platform)")
    args = ap.parse_args()
    vers = read(os.path.join(args.ref, "stock/vendor/etc/selinux/plat_sepolicy_vers.txt")).strip()
    c = Converter(args.ref, vers, keep_neverallows=args.neverallows == "keep")
    c.run()
    c.write(args.out)
    c.write_report(args.report)
    for k, v in c.report.items():
        print("%s: %s" % (k, v))
    if c.unsupported:
        print("UNSUPPORTED (%d):" % len(c.unsupported))
        for u in c.unsupported[:20]:
            print("  ", u)
    return 0


if __name__ == "__main__":
    sys.exit(main())
